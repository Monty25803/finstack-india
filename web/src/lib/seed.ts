function iso(day: number, hour = 12, minute = 10) {
  return new Date(2026, 9, day, hour, minute, 0).toISOString();
}

function tx(
  id: string,
  accountId: string,
  amount: number,
  type: TransactionType,
  mode: PaymentMode,
  merchant: string,
  category: SpendCategory,
  day: number,
  hour: number,
  minute: number,
): LedgerTransaction {
  const transactionDate = iso(day, hour, minute);
  return {
    id,
    userId: USER_ID,
    accountId,
    amount,
    transactionType: type,
    paymentMode: mode,
    merchantName: merchant,
    category,
    transactionDate,
    rawSmsHash: hashSms(`${id}:${merchant}:${amount}:${transactionDate}`),
  };
}

